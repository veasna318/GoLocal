function getLang() {
  try {
    return localStorage.getItem('golocal-lang') === 'km' ? 'km' : 'en';
  } catch {
    return 'en';
  }
}

function setLang(lang) {
  try {
    localStorage.setItem('golocal-lang', lang);
  } catch {}
  applyTranslations();
  window.dispatchEvent(new Event('langchange'));
}

function t(key) {
  return TEXT[getLang()][key] ?? TEXT.en[key] ?? key;
}

// Picks the Khmer name when Khmer is on and a Khmer name exists.
function localName(item, field = 'name') {
  if (!item) return '';
  const km = item[field + '_km'];
  const en = item[field + '_en'] ?? item[field];
  return getLang() === 'km' && km ? km : en;
}

function applyTranslations(root = document) {
  const lang = getLang();
  document.documentElement.lang = lang;
  document.documentElement.classList.toggle('lang-km', lang === 'km');
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  root.querySelectorAll('[data-i18n-label]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nLabel));
  });
}
